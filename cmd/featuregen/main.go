package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
)

func main() {
	root := flag.String("root", ".", "project root")
	flag.Parse()
	if err := generate(*root); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
func generate(root string) error {
	entries, err := os.ReadDir(filepath.Join(root, "features"))
	if err != nil {
		return err
	}
	names := []string{}
	valid := regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_]*$`)
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		if _, err := os.Stat(filepath.Join(root, "features", e.Name(), "feature.go")); os.IsNotExist(err) {
			continue
		} else if err != nil {
			return err
		}
		if !valid.MatchString(e.Name()) {
			return fmt.Errorf("invalid feature folder: %s", e.Name())
		}
		names = append(names, e.Name())
	}
	sort.Strings(names)
	var out bytes.Buffer
	out.WriteString("// Code generated by featuregen; DO NOT EDIT.\npackage features\nimport (\n\"personal-discord-bot/internal/feature\"\n")
	for i, name := range names {
		fmt.Fprintf(&out, "f%d %q\n", i, "personal-discord-bot/features/"+name)
	}
	out.WriteString(")\nfunc New(d feature.Dependencies)(*feature.Registry,error){return feature.New(\n")
	for i := range names {
		fmt.Fprintf(&out, "f%d.New(d),\n", i)
	}
	out.WriteString(")}\n")
	body, err := format.Source(out.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(root, "features", "catalog_generated.go"), body, 0644)
}
